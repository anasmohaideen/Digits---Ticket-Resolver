/** The sticky ticket tabs' height; the brief bar pins under it. */
export const STICKY_TABS_HEIGHT = 42;


const TONE_BY_VARIANT: Record<MessageNode['variant'], ResponseTone> = {
  'requester-reply': 'requester',
  reply: 'reply',
  forward: 'forward',
  'public-note': 'public-note',
  'private-note': 'private-note',
  'digit-message': 'worker',
  'concierge-message': 'worker'
};

/**
 * Option 2 of the Details tab, after the 21 Oct design review.
 *
 *   top card    One source of truth that leads with the artifact this stage
 *               needs (resolution › root cause › summary) — `ArtifactCard`.
 *   brief bar   One line under the sticky tabs once the card scrolls away.
 *   responses   The conversation is responses only. Past four of them, all
 *               but the latest two fold into "+N conversations", whoever
 *               wrote them and whenever they started.
 *   artifacts   Summary, root cause and resolution note are each an entry
 *               from Ticket Resolver, private to agents, with their work log.
 *   Ask AI      On private notes and AI entries only (`useAskAi`).
 *   reply       "Reply" opens an editor holding the suggested reply.
 *
 * Option 1 (`../DetailsTab.tsx`) is unchanged.
 */
/** Resolution notes a ticket's own story ends with. */
const AUTHORED_RESOLUTIONS: Record<string, ResolutionNote> = { 'INC-4155': INC_4155_RESOLUTION };

/** Summaries generated by clicking the empty card, where the ticket's own story has none. */
const ON_DEMAND_SUMMARIES: Record<string, SummaryCard> = { 'INC-4150': INC_4150_SUMMARY };

export default function DetailsTabOption2({
  tab: authoredTab,
  fullTab: fullTabProp,
  ticketType,
  reviewState = 'landing',
  proposed = DEFAULT_PROPOSED,
  scenario,
  internalStyle,
  askAi,
  incomingCount = 0,
  stage,
  locked = false,
  pickedUpAt,
  conversationExpired = false
}: {
  tab: TicketDetailsTab;
  /** The ticket as authored, before a journey stage cut it back; what asking for a result brings. */
  fullTab?: TicketDetailsTab;
  ticketType: TicketType;
  reviewState?: ReviewState;
  proposed?: ProposedFlags;
  scenario: ScenarioId;
  internalStyle: InternalStyle;
  askAi: AskAi;
  /** How many follow-ups the prototype control has sent from the requester. */
  incomingCount?: number;
  /** The Resolver journey stage being shown; absent for the full ticket. */
  stage?: StageId;
  /** The Digit still has the ticket: everything is read-only but the approval. */
  locked?: boolean;
  /** When the viewer took the ticket from the Digit with Pickup. */
  pickedUpAt?: string;
  /** The pre-ticket chat is past its 90 days and no longer kept. */
  conversationExpired?: boolean;
}) {
  const ticketCode = authoredTab.ticket.id;
  const fullTab = fullTabProp ?? authoredTab;

  /* What a person can ask for by clicking: a summary on the empty card, a root
     cause or a resolution note on the rows under it. Each thinks for a moment,
     then lands in the top card and in the timeline. */
  const summaryGen = useOnDemand();
  const rcaGen = useOnDemand();
  const noteGen = useOnDemand();
  const onDemandSummary = summaryOnDemand(ON_DEMAND_SUMMARIES[ticketCode], fullTab.summary, summaryGen.at);
  const summaryContent = onDemandSummary && applyFailureToSummary(onDemandSummary, stage);
  const rootCauseContent = ROOT_CAUSE_ON_DEMAND[ticketCode] ?? (fullTab.rootCause.state === 'found' ? fullTab.rootCause : undefined);
  const tab = useMemo<TicketDetailsTab>(() => {
    let next = authoredTab;
    if (summaryGen.phase === 'generating') next = { ...next, summary: { state: 'generating', elapsedSeconds: summaryGen.elapsed } };
    else if (summaryGen.phase === 'ready' && summaryContent) next = { ...next, summary: summaryContent };
    if (rcaGen.phase === 'generating') {
      next = { ...next, rootCause: { state: 'analyzing', live: { label: 'Comparing similar tickets and recent changes', elapsedSeconds: rcaGen.elapsed } } };
    } else if (rcaGen.phase === 'ready' && rootCauseContent) {
      next = { ...next, rootCause: { ...rootCauseContent, at: rcaGen.at, by: RESOLVER } };
    }
    return next;
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [authoredTab, summaryGen.phase, summaryGen.elapsed, summaryGen.at, rcaGen.phase, rcaGen.elapsed, rcaGen.at]);
  const defaults = composerDefaults(ticketCode, tab.ticket.requester.name);
  const story = hasScenarioData(tab.ticket.id);

  const [expanded, setExpanded] = useState(false);
  const [stripVisible, setStripVisible] = useState(false);
  const [composerOpen, setComposerOpen] = useState(false);
  const [sentReplies, setSentReplies] = useState<MessageNode[]>([]);
  const [incoming, setIncoming] = useState<MessageNode[]>([]);
  const [seenIncoming, setSeenIncoming] = useState<string[]>([]);
  const [approvalDecisions, setApprovalDecisions] = useState<Record<string, { state: ApprovalNode['state']; decidedAt: string }>>({});
  const contentStartRef = useRef<HTMLDivElement | null>(null);
  const cardRef = useRef<HTMLDivElement | null>(null);
  const deckRef = useRef<HTMLDivElement | null>(null);
  const [deckVisible, setDeckVisible] = useState(true);
  /* How much of the column's bottom the reply dock covers: just its buttons
     when closed, more with an editor open above them. */
  const [dockHeight, setDockHeight] = useState(72);

  const review = useMemo(() => buildReviewView(tab, reviewState), [tab, reviewState]);
  const timeline = useMemo(
    () => buildResponseTimeline(story ? [...review.stream, ...scenarioStream(scenario)] : review.stream),
    [review.stream, story, scenario]
  );

  /* Asked-about notes and sent replies are live state, so they are merged in
     here rather than in the pure timeline. */
  const entries = useMemo<ResponseEntry[]>(() => {
    /* Ask AI happens in the side pane only: its questions never become notes here. */
    const base = cutEntries(timeline.entries, stage).map((entry) => (entry.kind === 'event' ? applyBlockerToEvent(entry, stage) : entry));
    /* A failed job leaves the ticket with a group, and then a person. */
    const failed = stage === 'triage-failed' || stage === 'rca-failed' ? stage : undefined;
    const afterFailure = failed && base.length ? handoverAfterFailure(failed, tab.viewer.agent, base[base.length - 1].at) : [];
    const generated: ArtifactEntry[] = (
      [['summary', summaryGen], ['root-cause', rcaGen], ['resolution', noteGen]] as const
    ).flatMap(([artifact, gen]) => (gen.phase === 'ready' && gen.at
      ? [{ kind: 'artifact' as const, id: `gen-${artifact}`, at: gen.at, actor: RESOLVER, artifact }]
      : []));
    /* Pickup takes the ticket from the Digit, as an agent picking it up from a queue. */
    const pickup: EventNode[] = pickedUpAt
      ? [{ kind: 'event', id: 'o2-pickup', at: pickedUpAt, actor: tab.viewer.agent, type: 'delegated', data: { target: tab.viewer.agent, method: 'manual' } }]
      : [];
    return [...base, ...afterFailure, ...generated, ...pickup, ...sentReplies, ...incoming]
      .filter((entry) => entry.kind !== 'approval')
      .sort((x, y) => Date.parse(x.at) - Date.parse(y.at));
  }, [timeline.entries, askAi.threads, sentReplies, incoming, stage, summaryGen.phase, rcaGen.phase, noteGen.phase, pickedUpAt]);

  const workFor = (id: string) => (timeline.workById[id] ?? []).map((event) => applyBlockerToEvent(event, stage));

  /* The replay reads these when it starts, so state it adds mid-run does not
     restart it. */
  const entriesRef = useRef(entries);
  entriesRef.current = entries;
  const workRef = useRef(timeline.workById);
  workRef.current = timeline.workById;

  const findPendingApprovals = (nodes: StreamNode[]): ApprovalNode[] => nodes.flatMap((node) =>
    node.kind === 'group'
      ? findPendingApprovals(node.children)
      : node.kind === 'approval' && node.state === 'pending'
        ? [node]
        : []);
  const authoredPendingApprovals = findPendingApprovals(review.stream);
  const scenarioPending = stage === 'approval' ? [PROFILE_APPROVAL] : story && !stage ? scenarioApprovals(scenario) : [];
  const approvals = [...authoredPendingApprovals, ...scenarioPending];
  const approvalState = (approval: ApprovalNode) => approvalDecisions[approval.id]?.state ?? approval.state;
  const pendingApprovals = approvals.filter((approval) => approvalState(approval) === 'pending');
  const decideApproval = (approval: ApprovalNode, state: ApprovalNode['state']) => {
    setApprovalDecisions((current) => ({ ...current, [approval.id]: { state, decidedAt: new Date().toISOString() } }));
  };

  const latestWorker = [...entries].reverse().find((entry): entry is MessageNode =>
    entry.kind === 'message' && entry.actor.kind === 'digit');
  /** The agent's decision, as a line in the work log it unblocked. */
  const decisionEvent = (approval: ApprovalNode, state: 'approved' | 'rejected', at: string): EventNode => {
    const acceptedFields = state === 'approved' ? approval.proposedFields : undefined;
    return {
      kind: 'event',
      id: `${approval.id}-decision`,
      at,
      actor: tab.viewer.agent,
      type: acceptedFields ? 'properties-updated' : 'approval-decided',
      data: acceptedFields
        ? { count: acceptedFields.length, fields: acceptedFields }
        : { decision: state, object: [approval.title] }
    };
  };

  const approvalDecisionEvents: EventNode[] = approvals.flatMap((approval) => {
    const decision = approvalDecisions[approval.id];
    if (!decision || decision.state === 'pending') return [];
    const state = decision.state;
    const existingWork = latestWorker ? workFor(latestWorker.id) : [];
    return [decisionEvent(approval, state, existingWork[existingWork.length - 1]?.at ?? approval.at)];
  });

  const resolution = story && scenario === '4'
    ? RESOLUTION_NOTE
    : AUTHORED_RESOLUTIONS[ticketCode] ?? (noteGen.phase === 'ready' ? resolutionOnDemand(ticketCode, noteGen.at) : undefined);
  /* Deleting a tab removes it; the next one takes its place, and with none
     left the card falls back to its empty state. */
  const [deleted, setDeleted] = useState<ArtifactKind[]>([]);
  const takeover = useTakeover();
  const available = availableArtifacts(tab, Boolean(resolution)).filter((kind) => !deleted.includes(kind));
  /* The card always opens on Summary when there is one. */
  const lead = available.includes('summary') ? 'summary' : leadArtifact(available);
  const [selectedArtifact, setActive] = useState<ArtifactKind>(lead);
  // Deleting the selected tab must switch the body even when the preferred
  // lead (usually Summary) did not change. Never render a deleted artifact.
  const active = available.includes(selectedArtifact) ? selectedArtifact : lead;
  useEffect(() => setActive(lead), [lead]);
  /* What was just asked for is what the card shows. */
  useEffect(() => { if (rcaGen.phase !== 'idle') setActive('root-cause'); }, [rcaGen.phase]);
  useEffect(() => { if (noteGen.phase === 'ready') setActive('resolution'); }, [noteGen.phase]);
  const [forward, setForward] = useState<{ id: number; text: string } | undefined>();

  const generateArtifact = (kind: ArtifactKind) => takeover(() => {
    setDeleted((current) => current.filter((item) => item !== kind));
    setActive(kind);
    if (kind === 'summary') summaryGen.start();
    else if (kind === 'root-cause') rcaGen.start();
    else noteGen.start();
  });

  /* Slim rows under the top card for what a person can ask for when the Digit
     did not produce it. */
  /* Asking for work is a change, so while the Digit has the ticket it goes
     through the take-over guard first. */
  const ambientRows: AmbientRow[] = [
    ...(available.length > 0 && !available.includes('summary') && summaryContent && tab.summary.state !== 'generating'
      ? [{ id: 'summary', label: 'Summarize ticket', onClick: () => generateArtifact('summary') }]
      : []),
    ...(tab.summary.state !== 'not-generated' && tab.summary.state !== 'generating' && !available.includes('root-cause') && tab.rootCause.state !== 'analyzing' && rcaGen.phase !== 'generating' && rootCauseContent
      ? [{ id: 'rca', label: 'Find the likely cause and resolution steps', onClick: () => generateArtifact('root-cause') }]
      : []),
    ...(tab.rootCause.state === 'found' && !available.includes('resolution') && (resolution || hasResolutionOnDemand(ticketCode))
      ? [{ id: 'note', label: 'Generate a resolution note', busy: noteGen.phase === 'generating', busyLabel: 'Writing the resolution note', seconds: noteGen.elapsed, onClick: () => generateArtifact('resolution') }]
      : [])
  ];

  /* Before the ticket existed, the conversation was chat. What the requester
     saw is kept as a read-only record at the foot of the top card; the
     conversation below starts where the ticket does. */
  const createdEvent = useMemo(() => ticketCreatedEvent(review.stream), [review.stream]);
  const createdAt = createdEvent?.at;
  const split = useMemo(() => splitAtCreation(entries, createdAt), [entries, createdAt]);
  const logMessages = useMemo(() => requesterVisible(split.before), [split.before]);

  /* The fold stays in the rows once opened, so opening it can animate: the
     pill eases away and the earlier messages ease in, in the same place. */
  const rows = useMemo(
    () => collapseResponses(split.after),
    [split.after]
  );

  /* The bar stands in for the card, so it shows exactly when the card has gone
     up behind the sticky tabs. */
  useEffect(() => {
    const card = cardRef.current;
    const scroller = card?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!card || !scroller) return;
    const observer = new IntersectionObserver(
      ([entry]) => {
        const rootTop = entry.rootBounds?.top ?? 0;
        setStripVisible(!entry.isIntersecting && entry.boundingClientRect.top < rootTop);
      },
      { root: scroller, threshold: 0, rootMargin: `-${STICKY_TABS_HEIGHT}px 0px 0px 0px` }
    );
    observer.observe(card);
    return () => observer.disconnect();
  }, []);

  /* Approvals wait as the last card in the conversation. */
  const deckApprovals = pendingApprovals;
  /* The public-reply demo (S3) is about the reply, so the approval stays out of it. */
  const hideDeck = story && scenario === '3';
  const showDeck = !hideDeck && deckApprovals.length > 0;

  /* The floating pill stands in for the card once it has scrolled out of view
     (behind the sticky tabs above, or the reply dock below). */
  useEffect(() => {
    const deck = deckRef.current;
    const scroller = deck?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!showDeck || !deck || !scroller) {
      setDeckVisible(true);
      return;
    }
    const observer = new IntersectionObserver(
      ([entry]) => setDeckVisible(entry.isIntersecting),
      { root: scroller, threshold: 0.2, rootMargin: `-${STICKY_TABS_HEIGHT}px 0px -${dockHeight}px 0px` }
    );
    observer.observe(deck);
    return () => observer.disconnect();
  }, [showDeck, deckApprovals.length, dockHeight]);

  /* Follow-ups from the prototype control: each click lands one more message
     from the requester, up to MAX_INCOMING. */
  const nearBottom = useRef(true);
  const incomingIds = useRef<string[]>([]);
  useEffect(() => {
    const scroller = contentStartRef.current?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!scroller) return;
    const update = () => {
      const gap = scroller.scrollHeight - scroller.clientHeight - scroller.scrollTop;
      nearBottom.current = gap < 160;
      /* At the very end everything is in view, whatever the dock covers. */
      if (gap < 40 && incomingIds.current.length) {
        setSeenIncoming((current) => [...new Set([...current, ...incomingIds.current])]);
      }
    };
    update();
    scroller.addEventListener('scroll', update, { passive: true });
    return () => scroller.removeEventListener('scroll', update);
  }, []);

  useEffect(() => {
    const target = Math.min(incomingCount, MAX_INCOMING);
    setIncoming((current) => {
      if (target <= current.length) return target === current.length ? current : current.slice(0, target);
      const next = [...current];
      while (next.length < target) {
        next.push(incomingMessage(next.length, ticketCode, tab.ticket.requester, tab.ticket.source));
      }
      return next;
    });
    if (target === 0) setSeenIncoming([]);
  }, [incomingCount, ticketCode, tab.ticket.requester, tab.ticket.source]);

  /* Reading at the end of the conversation, a new message just arrives and the
     column stays pinned to it. Scrolled up, it stays where it is and the pill
     below takes over. */
  useLayoutEffect(() => {
    incomingIds.current = incoming.map((message) => message.id);
    if (incoming.length === 0 || !nearBottom.current) return;
    /* Pinned to the end, so it is read on arrival: no pill, not even for a frame. */
    setSeenIncoming((current) => [...new Set([...current, ...incomingIds.current])]);
    const scroller = contentStartRef.current?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    requestAnimationFrame(() => scroller?.scrollTo({ top: scroller.scrollHeight, behavior: reduced ? 'auto' : 'smooth' }));
  }, [incoming.length]);

  /* A message counts as read once most of it has been on screen, clear of the
     sticky tabs above and the reply dock below. */
  useEffect(() => {
    const scroller = contentStartRef.current?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!scroller || incoming.length === 0) return;
    const observer = new IntersectionObserver(
      (records) => {
        const ids = records.filter((record) => record.isIntersecting).map((record) => (record.target as HTMLElement).dataset.incomingId ?? '');
        if (ids.length) setSeenIncoming((current) => [...new Set([...current, ...ids.filter(Boolean)])]);
      },
      { root: scroller, threshold: 0.3, rootMargin: `-${STICKY_TABS_HEIGHT}px 0px -${dockHeight}px 0px` }
    );
    incoming.forEach((message) => {
      const node = document.getElementById(`stream-${message.id}`);
      if (node) {
        node.dataset.incomingId = message.id;
        observer.observe(node);
      }
    });
    return () => observer.disconnect();
  }, [incoming, dockHeight]);

  const unseenIncoming = incoming.filter((message) => !seenIncoming.includes(message.id));

  /* Takes the agent to the first message they haven't seen, with a brief ring. */
  const scrollToIncoming = useCallback(() => {
    const first = incoming.find((message) => !seenIncoming.includes(message.id));
    const node = first ? document.getElementById(`stream-${first.id}`) : null;
    const scroller = node?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!node || !scroller) return;
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const delta = node.getBoundingClientRect().top - scroller.getBoundingClientRect().top - STICKY_TABS_HEIGHT - 16;
    scroller.scrollBy({ top: delta, behavior: reduced ? 'auto' : 'smooth' });
    node.classList.remove('tr-o2-flash');
    void node.offsetWidth;
    node.classList.add('tr-o2-flash');
    window.setTimeout(() => node.classList.remove('tr-o2-flash'), 1700);
  }, [incoming, seenIncoming]);

  /* The requester's latest message, quoted under an email reply. */
  const quoted = (() => {
    const last = [...entries].reverse().find((entry): entry is MessageNode => entry.kind === 'message' && entry.actor.kind === 'requester');
    const toText = (body: MessageNode['body']) => body.map((part) => (typeof part === 'string' ? part : part.label)).join('\n\n');
    /* With no reply yet, what the requester first wrote is what an email quotes. */
    if (!last) return tab.ticket.source === 'email' ? { from: tab.ticket.requester.name, text: toText(tab.description.body) } : undefined;
    return { from: last.actor.name, text: toText(last.body) };
  })();

  /* Brings the approval into the part of the column the dock isn't covering,
     with its buttons clear of the editor. A card taller than that room is
     aligned to the top instead. */
  const scrollToDeck = useCallback(() => {
    const deck = deckRef.current;
    const scroller = deck?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!deck || !scroller) return;
    const card = deck.getBoundingClientRect();
    const view = scroller.getBoundingClientRect();
    const gap = 16;
    const room = view.height - STICKY_TABS_HEIGHT - dockHeight - gap * 2;
    const delta = card.height <= room
      ? card.bottom - (view.bottom - dockHeight - gap)
      : card.top - view.top - STICKY_TABS_HEIGHT - gap;
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    scroller.scrollBy({ top: delta, behavior: reduced ? 'auto' : 'smooth' });
  }, [dockHeight]);

  const scrollToCard = useCallback(() => {
    const card = cardRef.current;
    const scroller = card?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!card || !scroller) return;
    const top = card.getBoundingClientRect().top - scroller.getBoundingClientRect().top + scroller.scrollTop - STICKY_TABS_HEIGHT - 16;
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    scroller.scrollTo({ top: Math.max(0, top), behavior: reduced ? 'auto' : 'smooth' });
  }, []);

  /* Land an incident at its newest response; a service request at the top. */
  useEffect(() => {
    const scroller = contentStartRef.current?.closest<HTMLElement>('[data-ticket-conversation-scroller]');
    if (!scroller) return;
    /* Consumption (S1) and service requests are read from the top; the demos
       that act on the conversation land at its end, by the editor. */
    const startAtTop = ticketType === 'Service Request' || scenario === '1';
    const toTarget = () => {
      scroller.scrollTop = startAtTop ? 0 : scroller.scrollHeight;
    };
    const frame = requestAnimationFrame(toTarget);
    /* Cards that size themselves after first paint (the approval, its fields)
       add height once the first scroll is done. Settle once more, but only
       while the agent hasn't scrolled away from where we put them. */
    const settle = window.setTimeout(() => {
      if (startAtTop) return;
      const gap = scroller.scrollHeight - scroller.clientHeight - scroller.scrollTop;
      if (gap > 0 && gap < 120) toTarget();
    }, 350);
    return () => {
      cancelAnimationFrame(frame);
      window.clearTimeout(settle);
    };
  }, [tab.ticket.id, ticketType, reviewState, scenario]);

  const visibleRows = rows;

  /* From the reference build: one home per fact. The pinned card holds the
     current Summary and Root cause in full; the thread keeps only the moment
     each was produced, as an activity row whose View takes the reader back to
     the card with that tab selected. Resolution notes use the same pointer. */
  const ARTIFACT_EVENT_TYPE = { summary: 'summary-updated', 'root-cause': 'root-cause-added', resolution: 'resolution-notes' } as const;
  const renderArtifactPointer = (entry: ArtifactEntry) => {
    const label = ARTIFACT_LABEL[entry.artifact].toLowerCase();
    /* The same action icon as the event it stands for. */
    const asEvent: EventNode = { kind: 'event', id: entry.id, at: entry.at, actor: entry.actor, type: ARTIFACT_EVENT_TYPE[entry.artifact], data: {} };
    return (
      <ActivityRow
        id={entry.id}
        actor={entry.actor}
        at={entry.at}
        icon={<EventLeadingIcon event={asEvent} />}
        text={<>{activityPerson(entry.actor)} {entry.artifact === 'summary' ? 'updated the' : 'added a'} <strong>{label}</strong></>}
        ticketCode={ticketCode}
        view={{
          ariaLabel: `View the ${label} in the pinned card`,
          onClick: () => {
            setActive(entry.artifact);
            requestAnimationFrame(scrollToCard);
          }
        }}
      />
    );
  };

  const renderMessage = (message: MessageNode) => {
    const tone = TONE_BY_VARIANT[message.variant];
    /* An agent replying to a Slack ticket replies in Slack, so their card
       carries the channel badge the Digit's and the requester's already do. */
    const showChannel = tone === 'worker' || tone === 'requester' || tone === 'reply';
    return (
      <ResponseCard
        id={message.id}
        actor={message.actor}
        at={message.at}
        tone={tone}
        internalStyle={internalStyle}
        channel={showChannel ? message.channel : undefined}
        work={[
          ...workFor(message.id),
          ...(message.id === latestWorker?.id ? approvalDecisionEvents : [])
        ]}
        ticketCode={ticketCode}
        >
        {message.to && message.to.length > 0 && (
          <div className="tr-o2-mail-meta">
            <span>{message.variant === 'forward' ? 'Forwarded to' : 'To'} {message.to.join(', ')}</span>
            {message.cc && message.cc.length > 0 && <span>Cc {message.cc.join(', ')}</span>}
            {message.bcc && message.bcc.length > 0 && <span>Bcc {message.bcc.join(', ')}</span>}
          </div>
        )}
        {message.notify && message.notify.length > 0 && (
          <div className="tr-o2-mail-meta"><span>Notified {message.notify.join(', ')}</span></div>
        )}
        <RichTextView value={message.body} ticketCode={ticketCode} />
        {message.attachments && message.attachments.length > 0 && (
          <div className="tr-o2-card-files">
            <AttachmentTiles attachments={message.attachments} showSnippets />
          </div>
        )}
      </ResponseCard>
    );
  };

  /* "A assigned it to B" and status changes: the system private-note variant,
     a message card without its border, fill or padding. The why sits under
     the chevron, as the work log does on the cards. */
  const renderEvent = (entry: EventNode) => {
    const event = assignmentEvent(entry);
    const standard = standardDetails(event);
    return (
      <ActivityRow
        id={event.id}
        actor={event.actor}
        at={event.at}
        icon={<EventLeadingIcon event={event} />}
        text={eventLine(event, ticketCode, false, activityPerson)}
        meta={standard.routing}
        details={hasStandardDetails(standard, event) ? <EventDetailsPane event={event} details={standard} ticketCode={ticketCode} /> : undefined}
        ticketCode={ticketCode}
      />
    );
  };

  const renderEntry = (entry: ResponseEntry) => {
    if (entry.kind === 'event') return renderEvent(entry);
    if (entry.kind === 'artifact') {
      return renderArtifactPointer(entry);
    }
    if (entry.kind === 'message') return renderMessage(entry);
    return null;
  };

  return (
    <div className="tr-details-tab tr-o2" style={{ display: 'flex', flexDirection: 'column' }}>
      <ArtifactStrip
        kind={active}
        line={available.length > 0 ? briefLine(active, tab, resolution) : ''}
        visible={stripVisible && available.length > 0}
        onExpand={scrollToCard}
      />

      <div ref={contentStartRef} className="tr-o2-content">
        <div ref={cardRef}>
          <ArtifactCard
            tab={tab}
            ticketCode={ticketCode}
            proposed={proposed}
            available={available}
            active={active}
            onChange={setActive}
            resolution={resolution}
            internalStyle={internalStyle}
            log={logMessages}
            onForward={isEmailLike(tab.ticket.source) ? (text) => setForward((current) => ({ id: (current?.id ?? 0) + 1, text })) : undefined}
            onDelete={(kind) => setDeleted((current) => [...current, kind])}
            onRegenerate={() => generateArtifact(active)}
            onGenerate={summaryContent ? () => generateArtifact('summary') : undefined}
          />
          <AmbientRows rows={ambientRows} />
        </div>

        <DescriptionBox
          description={tab.description}
          ticketCode={ticketCode}
          log={logMessages}
          requesterName={tab.ticket.requester.name}
          requester={tab.ticket.requester}
          channel={tab.ticket.source}
          conversationExpired={conversationExpired}
          attachments={ticketType === 'Service Request' ? SR_ATTACHMENTS.map(({ name, sizeLabel }) => ({ name, sizeLabel })) : undefined}
        />
        {ticketType === 'Service Request' && <RequestedItemsTable initialItems={SR_ITEMS} />}

        <ConversationsHeader>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 'var(--spacing-200)' }}>
            {visibleRows.map((row) => {
              if (row.kind === 'collapsed') {
                return (
                  <div key={row.id} className="tr-o2-fold">
                    <Reveal open={!expanded}>
                      <MessagesPill hidden={row.hidden} onExpand={() => setExpanded(true)} />
                    </Reveal>
                    <Reveal open={expanded} className="tr-o2-fold-body">
                      {row.hidden.map((entry) => <Fragment key={entry.id}>{renderEntry(entry)}</Fragment>)}
                    </Reveal>
                  </div>
                );
              }
              return <Fragment key={row.entry.id}>{renderEntry(row.entry)}</Fragment>;
            })}

            {showDeck && (
              <div ref={deckRef}>
                <ApprovalInline
                  key="pending"
                  approvals={deckApprovals}
                  ticketCode={ticketCode}
                  onDecide={decideApproval}
                />
              </div>
            )}

          </div>
        </ConversationsHeader>

        {/* A direct child of the content column, not of the conversation list:
            the dock sticks to the bottom of whatever it is inside, so it has
            to be inside something tall enough to hold an open editor. */}
      {(
        <ReplyComposer
          requester={tab.ticket.requester}
          agent={tab.viewer.agent}
          quoted={quoted}
          original={tab.ticket.source === 'email' ? { from: tab.ticket.requester.name, text: tab.description.body.map((part) => (typeof part === 'string' ? part : part.label)).join('\n\n') } : undefined}
          subject={tab.ticket.subject}
          ticketCode={ticketCode}
          source={tab.ticket.source}
          suggested={defaults.reply}
          defaults={defaults}
          forward={forward}
          open={composerOpen}
          onDockHeight={setDockHeight}
          onOpenChange={setComposerOpen}
          onAskAi={askAi.openPanel}
          askPaneOpen={Boolean(askAi.openThread)}
          onToggleAskPane={() => (askAi.openThread ? askAi.close() : askAi.openPanel())}
          locked={locked}
          pill={(showDeck && !deckVisible) || unseenIncoming.length > 0 ? (
            <PillRow>
              {unseenIncoming.length > 0 && <NewMessagePill count={unseenIncoming.length} onClick={scrollToIncoming} />}
              {showDeck && !deckVisible && <ApprovalPill count={deckApprovals.length} onClick={scrollToDeck} />}
            </PillRow>
          ) : undefined}
          onSend={(text, mode, recipients) => setSentReplies((current) => [
            ...current,
            {
              kind: 'message',
              id: `o2-sent-${current.length + 1}`,
              at: new Date().toISOString(),
              actor: tab.viewer.agent,
              variant: mode === 'note' ? (recipients?.visibility === 'public' ? 'public-note' : 'private-note') : mode === 'forward' ? 'forward' : 'reply',
              channel: tab.ticket.source,
              ...(recipients?.to ? { to: recipients.to, cc: recipients.cc, bcc: recipients.bcc } : {}),
              ...(recipients?.notify?.length ? { notify: recipients.notify } : {}),
              body: [text],
              flags: mode === 'reply' && (text === SUGGESTED_REPLY || text === SUGGESTED_REPLY_SHORT)
                ? { draftedWithCopilot: 'as-is' }
                : undefined
            }
          ])}
        />
      )}
      </div>
    </div>
  );
}
