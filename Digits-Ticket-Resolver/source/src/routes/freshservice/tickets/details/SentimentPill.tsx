import { useEffect, useRef, useState } from 'react';
import { Icon, IconButton } from '@freshworks/dew-components';

type Sentiment = 'Neutral' | 'Negative' | 'Positive';
type SentimentDetails = {
  before: Sentiment;
  now: Sentiment;
  explanation: string;
  influence: string;
};

const emoji: Record<Sentiment, string> = { Neutral: '😐', Negative: '😡', Positive: '😄' };

function detailsForTicket(code: string, subject: string): SentimentDetails {
  if (code === 'INC-4127') return {
    before: 'Negative',
    now: 'Positive',
    explanation: 'Repeated Corp-Secure Wi-Fi failures blocked Megan from Jira and other internal tools before her client demo. She is now connected to Guest Wi-Fi and has received an explanation of the cause and next steps.',
    influence: 'Infrastructure · Wi-Fi certificate and network access'
  };
  if (code === 'INC-4133') return {
    before: 'Negative',
    now: 'Neutral',
    explanation: 'Repeated Outlook password prompts interrupted Daniel’s work. He shared a screenshot and the Identity team is checking sign-in logs, but a fix has not been confirmed.',
    influence: 'Software · Outlook sign-in reliability'
  };
  if (code === 'INC-4140') return {
    before: 'Negative',
    now: 'Neutral',
    explanation: 'Elena can’t reach the expense app from the office and has a same-day quarter-end deadline. She understands the cause and that a person has to approve a change, but nothing is fixed yet.',
    influence: 'Network · firewall allow-list and the quarter-end change freeze'
  };
  if (code === 'INC-4142') return {
    before: 'Negative',
    now: 'Neutral',
    explanation: 'Marcus’s MacBook keeps restarting mid-call with customers on the line. He accepted that the cause isn’t confirmed and is waiting for the Hardware team to collect logs.',
    influence: 'Hardware · unexplained restarts during video calls'
  };
  return {
    before: 'Neutral',
    now: 'Neutral',
    explanation: `The current ticket updates about ${subject.toLowerCase()} do not establish a clear change in the requester’s sentiment.`,
    influence: 'Ticket conversation'
  };
}

export default function SentimentPill({ code, subject }: { code: string; subject: string }) {
  const [open, setOpen] = useState(false);
  const [feedback, setFeedback] = useState<'up' | 'down' | null>(null);
  const closeTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const details = detailsForTicket(code, subject);

  useEffect(() => () => { if (closeTimer.current) clearTimeout(closeTimer.current); }, []);

  const keepOpen = () => {
    if (closeTimer.current) clearTimeout(closeTimer.current);
    closeTimer.current = null;
    setOpen(true);
  };
  const closeSoon = () => {
    if (closeTimer.current) clearTimeout(closeTimer.current);
    closeTimer.current = setTimeout(() => { setOpen(false); closeTimer.current = null; }, 200);
  };

  return (
    <span className="ticket-sentiment" onMouseEnter={keepOpen} onMouseLeave={closeSoon}>
      <button type="button" className="ticket-sentiment-trigger" aria-expanded={open} aria-label={`Feeling ${details.now.toLowerCase()}. Show sentiment details`} onClick={() => setOpen(value => !value)} onFocus={() => setOpen(true)} onBlur={event => { if (!event.currentTarget.parentElement?.contains(event.relatedTarget)) setOpen(false); }}>
        <span aria-hidden="true">{emoji[details.now]}</span> Feeling {details.now.toLowerCase()}
      </button>
      {open && <div className="ticket-sentiment-popover" role="group" aria-label="Sentiment analysis" onMouseEnter={keepOpen} onKeyDown={event => { if (event.key === 'Escape') setOpen(false); }}>
        <div className="ticket-sentiment-comparison">
          <div><span>How they felt</span><strong className={`ticket-sentiment-value is-${details.before.toLowerCase()}`}>{emoji[details.before]} {details.before}</strong></div>
          <span className="ticket-sentiment-arrow" aria-hidden="true"><Icon name="ArrowRight" size="sm" /></span>
          <div><span>How they feel now</span><strong className={`ticket-sentiment-value is-${details.now.toLowerCase()}`}>{emoji[details.now]} {details.now}</strong></div>
        </div>
        <p>{details.explanation}</p>
        <p><strong>What influenced:</strong> {details.influence}</p>
        <div className="ticket-sentiment-footer"><span>Generated by AI, can be inaccurate.</span><div>
          <IconButton iconName={feedback === 'up' ? 'Actions/UpvoteFilled' : 'Actions/Upvote'} aria-label="Helpful sentiment analysis" aria-pressed={feedback === 'up'} size="mini" onClick={() => setFeedback('up')} />
          <IconButton iconName={feedback === 'down' ? 'Actions/DownvoteFilled' : 'Actions/Downvote'} aria-label="Unhelpful sentiment analysis" aria-pressed={feedback === 'down'} size="mini" onClick={() => setFeedback('down')} />
        </div></div>
      </div>}
    </span>
  );
}
